/**
 * Whale Club's own glyphs: the signs a thing wears in its bubble.
 *
 * Every glyph is drawn by hand for a 24 grid with a 2 px safe margin, in
 * strokes of 1.75 with round caps and joins, corners no tighter than 1.5,
 * one colour (currentColor, cream in a bubble), and no fills but a few
 * small dots. One idea per glyph, few strokes, so each reads at 20 px.
 * Libraries were looked at for what reads, never copied from
 * (docs/brand/BRAND.md).
 *
 * `words` are what a name is matched against, in English and Lithuanian,
 * without diacritics (match.ts strips them from the name too). A word of
 * four letters or more also matches as the start of a longer word, which
 * covers Lithuanian endings: "begi" finds "begimas", "begioti". A word
 * marked `~` is weak: it usually only qualifies another ("morning run",
 * "groti smuiku"), so it counts only when nothing stronger fits.
 */
export type GlyphGroup = 'body' | 'mind' | 'craft' | 'home' | 'people' | 'care'

export interface Glyph {
  id: string
  group: GlyphGroup
  /** The name a person sees in the "more" list. */
  label: string
  words: readonly string[]
  /** Inner SVG for a 24 by 24 box; strokes inherit the colour. */
  svg: string
}

/** A dot: the one filled mark a glyph may carry. */
const dot = (x: number, y: number, r = 1.1): string =>
  `<circle cx="${String(x)}" cy="${String(y)}" r="${String(r)}" fill="currentColor" stroke="none"/>`

